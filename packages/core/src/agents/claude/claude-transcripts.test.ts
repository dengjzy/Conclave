import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { claudeTranscript, claudeTranscripts } from './claude-transcripts'

const SESSION = '0b6c1f9e-6a7d-4d0e-9f43-2a51c3e1b001'
const CWD = '/work/app'
const at = (second: number) => `2026-10-01T10:00:${String(second).padStart(2, '0')}.000Z`
const user = (uuid: string, parentUuid: string | null, second: number, content: unknown, extra: object = {}) =>
  ({ type: 'user', uuid, parentUuid, isSidechain: false, timestamp: at(second), cwd: CWD, sessionId: SESSION, message: { role: 'user', content }, ...extra })
const assistant = (uuid: string, parentUuid: string, second: number, id: string, block: object, extra: object = {}) =>
  ({ type: 'assistant', uuid, parentUuid, isSidechain: false, timestamp: at(second), cwd: CWD, sessionId: SESSION, message: { id, role: 'assistant', content: [block] }, ...extra })

// A session as Claude Code writes one: a prompt answered with thinking, a command and a reply; a
// prompt rewound and asked again as a slash command; the CLI's own records in between.
const LINES = [
  { type: 'queue-operation', operation: 'enqueue', timestamp: at(0), sessionId: SESSION, content: 'Fix the build' },
  user('u1', null, 1, 'Fix the build'),
  user('m1', 'u1', 1, '<local-command-caveat>Caveat: generated by local commands</local-command-caveat>', { isMeta: true }),
  assistant('a1', 'm1', 2, 'msg_1', { type: 'thinking', thinking: 'Look at the failing step', signature: 'sig' }),
  assistant('a2', 'a1', 3, 'msg_1', { type: 'tool_use', id: 'toolu_1', name: 'Bash', input: { command: 'pnpm build', description: 'Build it' } }),
  user('r1', 'a2', 4, [{ type: 'tool_result', tool_use_id: 'toolu_1', content: 'built in 2s', is_error: false }], { toolUseResult: { stdout: 'built in 2s' } }),
  assistant('a3', 'r1', 5, 'msg_2', { type: 'text', text: 'The build passes now.' }),
  { type: 'ai-title', aiTitle: 'Fix the build', sessionId: SESSION },
  user('x1', 'a3', 6, 'A question I took back'),
  assistant('x2', 'x1', 7, 'msg_3', { type: 'text', text: 'An answer nobody kept' }),
  { type: 'assistant', uuid: 's1', parentUuid: 'a3', isSidechain: true, timestamp: at(8), message: { id: 'msg_s', content: [{ type: 'text', text: 'subagent talk' }] } },
  user('u2', 'a3', 9, '<command-message>review</command-message>\n<command-name>/review</command-name>\n<command-args>pr 12</command-args>'),
  assistant('a4', 'u2', 10, 'msg_4', { type: 'tool_use', id: 'toolu_2', name: 'Edit', input: { file_path: '/work/app/a.ts', old_string: 'a', new_string: 'b' } }),
  user('r2', 'a4', 11, [{ type: 'text', text: '[Request interrupted by user for tool use]' }]),
  { type: 'custom-title', customTitle: 'Build fixes', sessionId: SESSION }
].map((line) => JSON.stringify(line))

describe('claudeTranscript', () => {
  it('shows the current branch as the chat would, prompts closed by their turns', () => {
    const { entries, messages } = claudeTranscript(LINES)
    expect(entries.map((entry) => [entry.item.kind, entry.item.id])).toEqual([
      ['user', 'u:u1'],
      ['reasoning', 'c:a1:0'],
      ['tool', 't:toolu_1'],
      ['assistant', 'c:a3:0'],
      ['turn', 'turn:u1'],
      ['user', 'u:u2'],
      ['tool', 't:toolu_2'],
      ['turn', 'turn:u2']
    ])
    expect(entries[2]!.item).toMatchObject({ name: 'Bash', title: 'pnpm build', description: 'Build it', status: 'done', output: 'built in 2s', execution: { status: 'completed' } })
    expect(entries[4]!.item).toMatchObject({ state: 'completed', providerRef: 'a3', durationMs: 4000 })
    expect(entries[5]!.item).toMatchObject({ text: '/review pr 12' })
    // Its result never came: the user stopped it, and the turn with it.
    expect(entries[6]!.item).toMatchObject({ name: 'Edit', status: 'interrupted', diffs: [{ path: '/work/app/a.ts', change: 'update' }] })
    expect(entries[7]!.item).toMatchObject({ state: 'interrupted', providerRef: 'a4' })
    expect(messages).toEqual([
      { at: Date.parse(at(1)), role: 'user', text: 'Fix the build', ref: 'u1' },
      { at: Date.parse(at(5)), role: 'assistant', text: 'The build passes now.', ref: 'u1' },
      { at: Date.parse(at(9)), role: 'user', text: '/review pr 12', ref: 'u2' }
    ])
  })

  // Compacting can come in the middle of a turn: the notice shows where it happened, the turn closing after.
  it('goes on across a compaction, which shows as a notice', () => {
    const lines = [
      user('u1', null, 1, 'Start'),
      assistant('a1', 'u1', 2, 'msg_1', { type: 'text', text: 'Started' }),
      { type: 'system', subtype: 'compact_boundary', uuid: 'c1', parentUuid: null, logicalParentUuid: 'a1', isSidechain: false, timestamp: at(3) },
      user('s1', 'c1', 3, 'This session is being continued from a previous conversation…', { isCompactSummary: true, isVisibleInTranscriptOnly: true }),
      user('u2', 's1', 4, 'Go on'),
      assistant('a2', 'u2', 5, 'msg_2', { type: 'text', text: 'Going on' })
    ].map((line) => JSON.stringify(line))
    expect(claudeTranscript(lines).entries.map((entry) => entry.item.id)).toEqual(['u:u1', 'c:a1:0', 'n:c1', 'turn:u1', 'u:u2', 'c:a2:0', 'turn:u2'])
  })
})

describe('claudeTranscripts', () => {
  let root: string

  beforeEach(() => {
    root = mkdtempSync(path.join(os.tmpdir(), 'conclave-claude-projects-'))
  })

  afterEach(() => {
    rmSync(root, { recursive: true, force: true })
  })

  it('lists sessions with something the user said, by the name they gave it', async () => {
    const folder = path.join(root, '-work-app')
    mkdirSync(path.join(folder, SESSION, 'subagents'), { recursive: true })
    writeFileSync(path.join(folder, `${SESSION}.jsonl`), `${LINES.join('\n')}\n`)
    writeFileSync(path.join(folder, SESSION, 'subagents', 'agent-1.jsonl'), `${LINES[1]}\n`)
    // Only the CLI's own turns: nothing to go on with.
    writeFileSync(path.join(folder, '1e0c0b45-2a0b-4c8e-8a39-6c2a0d4f9d10.jsonl'), `${JSON.stringify(user('m', null, 1, '<local-command-stdout>ok</local-command-stdout>'))}\n`)
    writeFileSync(path.join(folder, 'notes.jsonl'), `${LINES[1]}\n`)
    const sessions = await claudeTranscripts(() => root).scan()
    expect(sessions).toEqual([expect.objectContaining({ sessionId: SESSION, cwd: CWD, title: 'Build fixes', named: true, firstPrompt: 'Fix the build', startedAt: Date.parse(at(0)) })])
    expect((await claudeTranscripts(() => root).read(sessions[0]!.file)).entries).toHaveLength(8)
  })
})
